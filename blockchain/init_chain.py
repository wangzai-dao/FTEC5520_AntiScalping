#!/usr/bin/env python
"""Initialize the local private chain: generate test accounts + genesis.json + .env.

Corresponds to "Member 1: prepare classroom test accounts such as organizer / buyerA / buyerB /
verifier / attacker". This script is for local use only; the generated .env / genesis.json hold
private keys and addresses, and .env is excluded by .gitignore, so never push it to GitHub.

Usage:
    python blockchain/init_chain.py            # first-time init (refuses to overwrite if it exists)
    python blockchain/init_chain.py --force    # regenerate accounts and overwrite genesis (wipes chain data)
"""

from __future__ import annotations

import argparse
import json
import secrets
import shutil
import sys
from pathlib import Path

from eth_account import Account

ROOT = Path(__file__).resolve().parents[1]
CHAIN = ROOT / "blockchain"

CHAIN_ID = 1337
PERIOD = 2          # Clique block period (seconds)
BALANCE_ETH = 1000  # initial balance of every test account

ROLES = ["deployer", "organizer", "buyerA", "buyerB", "verifier", "attacker", "miner"]
GAS_LIMIT = "0x1c9c380"  # 30,000,000


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="overwrite the existing genesis and .env (destroys local chain data)")
    args = ap.parse_args()

    env_path = ROOT / ".env"
    genesis_path = CHAIN / "genesis.json"
    if (env_path.exists() or genesis_path.exists()) and not args.force:
        sys.exit(
            ".env or blockchain/genesis.json already exists.\n"
            "Re-run with --force to regenerate (this deletes the local chain data in blockchain/data)."
        )

    accounts = {}
    for role in ROLES:
        acct = Account.create(secrets.token_hex(32))
        accounts[role] = {
            "address": acct.address,
            "key": "0x" + acct.key.hex().removeprefix("0x"),
        }

    # ---- genesis.json -------------------------------------------------
    miner = accounts["miner"]["address"].lower().removeprefix("0x")
    alloc = {
        acc["address"].lower().removeprefix("0x"): {"balance": hex(BALANCE_ETH * 10**18)}
        for acc in accounts.values()
    }
    genesis = {
        "config": {
            "chainId": CHAIN_ID,
            "homesteadBlock": 0,
            "eip150Block": 0,
            "eip155Block": 0,
            "eip158Block": 0,
            "byzantiumBlock": 0,
            "constantinopleBlock": 0,
            "petersburgBlock": 0,
            "istanbulBlock": 0,
            "berlinBlock": 0,
            "londonBlock": 0,
            "clique": {"period": PERIOD, "epoch": 30000},
        },
        "difficulty": "0x1",
        "gasLimit": GAS_LIMIT,
        # Clique extradata: 32 bytes of 0x00 + signer address + 65 bytes of 0x00
        "extradata": "0x" + "00" * 32 + miner + "00" * 65,
        "alloc": alloc,
    }
    CHAIN.mkdir(parents=True, exist_ok=True)
    genesis_path.write_text(json.dumps(genesis, indent=2), "utf-8")

    # ---- helper files required to start the node ------------------------
    (CHAIN / "miner.key").write_text(accounts["miner"]["key"].removeprefix("0x") + "\n", "utf-8")
    (CHAIN / "miner.addr").write_text(accounts["miner"]["address"] + "\n", "utf-8")
    pw_path = CHAIN / "password.txt"
    if not pw_path.exists():
        pw_path.write_text("ftec5520\n", "utf-8")

    # ---- .env ---------------------------------------------------------
    lines = [
        "# Local private-chain connection config (generated by blockchain/init_chain.py, never commit to GitHub)",
        f"RPC_URL=http://127.0.0.1:8545",
        f"CHAIN_ID={CHAIN_ID}",
        "",
        "# Classroom test-account private keys (local demo only; a real product keeps keys with users)",
    ]
    for role, acc in accounts.items():
        lines.append(f"PRIVATE_KEY_{role.upper()}={acc['key']}")
    env_path.write_text("\n".join(lines) + "\n", "utf-8")

    if args.force and (CHAIN / "data").exists():
        shutil.rmtree(CHAIN / "data")
        print("[init] removed the old blockchain/data")

    print(f"[init] chainId={CHAIN_ID} clique period={PERIOD}s balance={BALANCE_ETH} ETH")
    for role, acc in accounts.items():
        print(f"[init] {role:<10} {acc['address']}")
    print(f"[init] genesis  -> {genesis_path}")
    print(f"[init] private key -> {env_path} (gitignored)")


if __name__ == "__main__":
    main()
